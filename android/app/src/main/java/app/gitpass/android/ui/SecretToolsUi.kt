@Composable
fun PasswordGenerator(session: VaultSession, epoch: Long, onApply: (String) -> Unit, onCancel: () -> Unit) {
    var length by remember { mutableIntStateOf(20) }
    var revision by remember { mutableIntStateOf(0) }
    var revealed by remember { mutableStateOf(false) }
    var generated by remember(length, revision) { mutableStateOf<String?>(null) }
    var failed by remember(length, revision) { mutableStateOf(false) }
    LaunchedEffect(length, revision, epoch) {
        val result = withContext(Dispatchers.IO) { runCatching { session.generatePassword(length, epoch) } }
        generated = result.getOrNull()
        failed = result.isFailure
    }
    AlertDialog(
        onDismissRequest = onCancel,
        title = { Text(stringResource(R.string.generator)) },
        text = { Column(verticalArrangement = Arrangement.spacedBy(12.dp)) {
            Text(stringResource(R.string.generator_length, length))
            Row {
                TextButton(enabled = length > 12, onClick = { session.noteActivity(); length-- }) { Text("−") }
                TextButton(enabled = length < 64, onClick = { session.noteActivity(); length++ }) { Text("+") }
            }
            Text(if (revealed) generated.orEmpty() else "••••••", modifier = Modifier.testTag("generated-value"))
            TextButton(onClick = { session.noteActivity(); revealed = !revealed }) { Text(stringResource(if (revealed) R.string.hide else R.string.reveal)) }
            TextButton(onClick = { session.noteActivity(); revision++ }) { Text(stringResource(R.string.regenerate)) }
            if (failed) Text(stringResource(R.string.generator_failed))
        } },
        confirmButton = { TextButton(enabled = generated != null, onClick = {
            session.enforceInactivity()
            val state = session.state.value
            if (state.unlocked && state.epoch == epoch) {
                generated?.let(onApply)
                session.noteActivity()
            } else onCancel()
        }) { Text(stringResource(R.string.apply_password)) } },
        dismissButton = { TextButton(modifier = Modifier.testTag("generator-cancel"), onClick = onCancel) { Text(stringResource(R.string.cancel_edit)) } },
    )
}

@Composable
fun LiveTotpField(label: String, session: VaultSession, itemId: String, fieldKey: String, epoch: Long,
                  revealed: Boolean, onToggle: () -> Unit) {
    var value by remember(itemId, fieldKey, epoch, revealed) { mutableStateOf<LiveCode?>(null) }
    var invalid by remember(itemId, fieldKey, epoch, revealed) { mutableStateOf(false) }
    LaunchedEffect(itemId, fieldKey, epoch, revealed) {
        if (!revealed) return@LaunchedEffect
        while (true) {
            val result = withContext(Dispatchers.IO) { runCatching { session.liveTotp(itemId, fieldKey, epoch) } }
            value = result.getOrNull()
            invalid = result.isFailure
            // Refresh on wall-second boundaries, including after clock corrections.
            // Native core computes the code from actual Unix time, not uptime.
            delay((1000L - System.currentTimeMillis().mod(1000L)).coerceIn(1L, 1000L))
        }
    }
    Card {
        Column(Modifier.padding(14.dp), verticalArrangement = Arrangement.spacedBy(6.dp)) {
            Text(label)
            Text(if (revealed) value?.code ?: "••••••" else "••••••", Modifier.testTag("live-totp"))
            if (revealed && invalid) Text(stringResource(R.string.invalid_totp))
            if (revealed) value?.let { Text(stringResource(R.string.totp_remaining, it.secondsRemaining)) }
            TextButton(onClick = onToggle) { Text(stringResource(if (revealed) R.string.hide else R.string.reveal)) }
        }
    }
}
