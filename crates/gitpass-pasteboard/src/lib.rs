//! nspasteboard.org marker types for secrets copied to the macOS pasteboard, so clipboard managers
//! (Raycast, Alfred, Maccy, Paste, …) and Universal Clipboard / Handoff do not record or sync them.
//! Only macOS writes markers; every other platform keeps the plain-text clipboard path.

/// Markers declared alongside a copied value. See <https://nspasteboard.org>.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct PasteboardMarkers {
    pub concealed: bool,
    pub transient: bool,
    pub auto_generated: bool,
}

impl PasteboardMarkers {
    /// A stored secret: password, TOTP code, card number, CVV, API credential.
    pub const SECRET: Self = Self { concealed: true, transient: true, auto_generated: false };
    /// A secret generated by gitpass itself (also concealed and transient).
    pub const GENERATED: Self = Self { concealed: true, transient: true, auto_generated: true };
}

#[cfg(target_os = "macos")]
mod mac {
    use super::PasteboardMarkers;
    use anyhow::{bail, Result};
    use objc2_app_kit::NSPasteboard;
    use objc2_foundation::{NSData, NSString};

    pub const CONCEALED_TYPE: &str = "org.nspasteboard.ConcealedType";
    pub const TRANSIENT_TYPE: &str = "org.nspasteboard.TransientType";
    pub const AUTO_GENERATED_TYPE: &str = "org.nspasteboard.AutoGeneratedType";
    pub(super) const PLAIN_TEXT_TYPE: &str = "public.utf8-plain-text";

    /// Replace the general pasteboard contents with `text` and declare `markers` on the item.
    pub fn write(text: &str, markers: PasteboardMarkers) -> Result<()> {
        write_to(&NSPasteboard::generalPasteboard(), text, markers)
    }

    pub(super) fn write_to(pb: &NSPasteboard, text: &str, markers: PasteboardMarkers) -> Result<()> {
        pb.clearContents();
        let empty = NSData::new();
        for (name, on) in [(CONCEALED_TYPE, markers.concealed), (TRANSIENT_TYPE, markers.transient), (AUTO_GENERATED_TYPE, markers.auto_generated)] {
            if on { pb.setData_forType(Some(&empty), &NSString::from_str(name)); }
        }
        if !pb.setString_forType(&NSString::from_str(text), &NSString::from_str(PLAIN_TEXT_TYPE)) {
            bail!("could not write the text to the pasteboard");
        }
        Ok(())
    }
}

#[cfg(target_os = "macos")]
pub use mac::write;

#[cfg(all(test, target_os = "macos"))]
mod tests {
    use super::*;
    use objc2_app_kit::NSPasteboard;
    use objc2_foundation::NSString;

    /// A per-process, per-test named pasteboard: never the user's general pasteboard.
    fn private_pasteboard(name: &str) -> objc2::rc::Retained<NSPasteboard> {
        let name = format!("org.gitpass.test.{}.{name}", std::process::id());
        NSPasteboard::pasteboardWithName(&NSString::from_str(&name))
    }

    fn types_of(pb: &NSPasteboard) -> Vec<String> {
        let Some(types) = pb.types() else { return vec![] };
        (0..types.count()).map(|i| types.objectAtIndex(i).to_string()).collect()
    }

    fn read_text(pb: &NSPasteboard) -> Option<String> {
        pb.stringForType(&NSString::from_str(mac::PLAIN_TEXT_TYPE)).map(|s| s.to_string())
    }

    #[test]
    fn secret_marks_concealed_and_transient() {
        let pb = private_pasteboard("secret");
        mac::write_to(&pb, "FAKE-secret", PasteboardMarkers::SECRET).unwrap();
        let types = types_of(&pb);
        assert!(types.iter().any(|t| t == mac::CONCEALED_TYPE), "{types:?}");
        assert!(types.iter().any(|t| t == mac::TRANSIENT_TYPE), "{types:?}");
        assert!(!types.iter().any(|t| t == mac::AUTO_GENERATED_TYPE), "{types:?}");
        assert_eq!(read_text(&pb).as_deref(), Some("FAKE-secret"));
        pb.clearContents();
    }

    #[test]
    fn generated_also_marks_auto_generated() {
        let pb = private_pasteboard("generated");
        mac::write_to(&pb, "FAKE-generated", PasteboardMarkers::GENERATED).unwrap();
        let types = types_of(&pb);
        assert!(types.iter().any(|t| t == mac::CONCEALED_TYPE), "{types:?}");
        assert!(types.iter().any(|t| t == mac::TRANSIENT_TYPE), "{types:?}");
        assert!(types.iter().any(|t| t == mac::AUTO_GENERATED_TYPE), "{types:?}");
        pb.clearContents();
    }

    #[test]
    fn plain_has_no_markers() {
        let pb = private_pasteboard("plain");
        mac::write_to(&pb, "plain text", PasteboardMarkers::default()).unwrap();
        let types = types_of(&pb);
        for marker in [mac::CONCEALED_TYPE, mac::TRANSIENT_TYPE, mac::AUTO_GENERATED_TYPE] {
            assert!(!types.iter().any(|t| t == marker), "{types:?}");
        }
        assert_eq!(read_text(&pb).as_deref(), Some("plain text"));
        pb.clearContents();
    }
}
